const REGISTRY_MAP = new Map<string, AircraftType>();
for (const item of HAA_FLEET_REGISTRY) {
  REGISTRY_MAP.set(item.tailNumber.toUpperCase(), item.type);
  REGISTRY_MAP.set(item.cleanTail.toUpperCase(), item.type);
}

/**
 * Automatically detect aircraft model/type from haa_fleet_list.txt
 * Supports with or without leading N (e.g. "18AC" or "N18AC" -> "172")
 */
export function detectAircraftTypeFromHaaList(inputTail: string): AircraftType | null {
  if (!inputTail) return null;
  const normalized = inputTail.trim().toUpperCase();
  const withoutN = normalized.replace(/^N/, "");
  return REGISTRY_MAP.get(normalized) || REGISTRY_MAP.get(withoutN) || null;
}

export function searchHaaRegistry(query: string, limit = 8): HaaRegistryEntry[] {
  if (!query || query.trim().length === 0) return [];
  const clean = query.trim().toUpperCase().replace(/^N/, "");
  return HAA_FLEET_REGISTRY.filter(item => 
    item.cleanTail.includes(clean) || item.tailNumber.includes(clean)
  ).slice(0, limit);
}
